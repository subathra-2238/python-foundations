# Python Tuples

student = ("Subathra", 18, "AI & ML")

print("Student:", student)

# Accessing elements
print("Name:", student[0])
print("Age:", student[1])
print("Department:", student[2])

# Tuple length
print("Number of values:", len(student))

# Loop through tuple
print("\nStudent Details:")

for value in student:
    print(value)